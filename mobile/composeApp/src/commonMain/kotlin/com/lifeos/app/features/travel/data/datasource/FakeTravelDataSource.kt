    fun getTripDetail(tripId: String): TripDetail? {
        savedTripDetails[tripId]?.let { return it }
        val trip = (upcomingTrips + pastTrips).find { it.id == tripId } ?: return null
        return if (tripId == TRIP_ID_CAPPADOCIA) cappadociaDetail(trip) else genericDetailFor(trip)
    }

    /**
     * Adds [detail] to Travel List's upcoming trips and remembers its full
     * generated content, so opening it from the list afterward shows what
     * was actually generated/saved — not [genericDetailFor]'s placeholder.
     */
    fun saveTrip(detail: TripDetail) {
        upcomingTrips.add(detail.trip)
        savedTripDetails[detail.trip.id] = detail
    }

    /**
