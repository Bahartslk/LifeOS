    fun getTravelList(): TravelListData = TravelListData(
        upcomingTrips = upcomingTrips,
        pastTrips = pastTrips,
        statistics = TravelStatistics(
            // Computed, not a fixed literal — a hardcoded "16" here silently
            // drifted out of sync the moment Cappadocia was added as a third
