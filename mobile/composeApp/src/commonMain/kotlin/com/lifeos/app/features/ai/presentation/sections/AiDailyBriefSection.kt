/**
 * "Günün Özeti" — the AI's focus suggestion, highlights, recommended task
 * order and motivation for today, all generated by the backend from the
 * user's own Planner and Travel data. Purely a display of
 * [DailyBriefUiState]; the refresh button only sends an event.
 */
@Composable
fun AiDailyBriefSection(
    state: DailyBriefUiState,
    onRefreshClick: () -> Unit,
    modifier: Modifier = Modifier,
) {
    AppCard(modifier = modifier.fillMaxWidth()) {
        Column(verticalArrangement = Arrangement.spacedBy(LifeOSSpacing.md)) {
            BriefHeader(isLoading = state.isLoading, onRefreshClick = onRefreshClick)

            val brief = state.brief
            when {
                state.isLoading && brief == null -> BodyText(AiAssistantStrings.BRIEF_LOADING, muted = true)
                brief != null -> BriefContent(brief)
            }
            if (state.errorMessage != null) {
                BodyText(state.errorMessage, color = MaterialTheme.colorScheme.error)
            } else if (brief != null && !brief.isComplete && !state.isLoading) {
                BodyText(AiAssistantStrings.BRIEF_PARTIAL_MESSAGE, muted = true)
            }
        }
    }
}

@Composable
private fun BriefHeader(isLoading: Boolean, onRefreshClick: () -> Unit) {
    Row(modifier = Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
        Text(
            text = AiAssistantStrings.BRIEF_TITLE,
            style = LifeOSTextStyles.overline,
            modifier = Modifier.weight(1f).semantics { heading() },
        )
        if (isLoading) {
            CircularProgressIndicator(modifier = Modifier.size(20.dp), strokeWidth = 2.dp)
        } else {
            IconButton(onClick = onRefreshClick) {
                Icon(
                    imageVector = Icons.Filled.Refresh,
                    contentDescription = AiAssistantStrings.BRIEF_REFRESH_DESCRIPTION,
                )
            }
        }
    }
}

@Composable
private fun BriefContent(brief: DailyBrief) {
    Column(verticalArrangement = Arrangement.spacedBy(LifeOSSpacing.md)) {
        brief.motivation?.let { message ->
            LabeledBlock(AiAssistantStrings.BRIEF_MOTIVATION_TITLE) {
                Text(
                    text = message,
                    style = MaterialTheme.typography.bodyLarge,
                    color = MaterialTheme.colorScheme.primary,
                )
            }
        }
        brief.summary?.let { summary ->
            if (summary.suggestedFocus.isNotEmpty()) {
                LabeledBlock(AiAssistantStrings.BRIEF_FOCUS_TITLE) { BodyText(summary.suggestedFocus) }
            }
            if (summary.keyEvents.isNotEmpty()) {
                LabeledBlock(AiAssistantStrings.BRIEF_EVENTS_TITLE) {
                    summary.keyEvents.forEach { event -> BodyText("• $event") }
                }
            }
        }
        brief.priorities?.let { priorities ->
            LabeledBlock(AiAssistantStrings.BRIEF_PRIORITIES_TITLE) {
                if (priorities.isEmpty()) {
                    BodyText(AiAssistantStrings.BRIEF_EMPTY_PRIORITIES, muted = true)
                } else {
                    priorities.forEach { PriorityRow(it) }
                }
            }
        }
    }
}

@Composable
private fun PriorityRow(priority: DailyPriority) {
    Row(horizontalArrangement = Arrangement.spacedBy(LifeOSSpacing.sm)) {
        Text(
            text = "${priority.rank}.",
            style = MaterialTheme.typography.bodyMedium,
            fontWeight = FontWeight.SemiBold,
            color = MaterialTheme.colorScheme.primary,
        )
        Column {
            Text(
                text = priority.taskTitle,
                style = MaterialTheme.typography.bodyMedium,
                fontWeight = FontWeight.SemiBold,
            )
            if (priority.reason.isNotEmpty()) {
                BodyText(priority.reason, muted = true)
            }
        }
    }
}

@Composable
private fun LabeledBlock(title: String, content: @Composable () -> Unit) {
    Column(verticalArrangement = Arrangement.spacedBy(LifeOSSpacing.xs)) {
        Text(
            text = title,
            style = MaterialTheme.typography.titleSmall,
            modifier = Modifier.semantics { heading() },
        )
        content()
    }
}

@Composable
private fun BodyText(
    text: String,
    muted: Boolean = false,
    color: androidx.compose.ui.graphics.Color? = null,
) {
    Text(
        text = text,
        style = MaterialTheme.typography.bodyMedium,
        color = color ?: if (muted) MaterialTheme.colorScheme.onSurfaceVariant else MaterialTheme.colorScheme.onSurface,
    )
}

