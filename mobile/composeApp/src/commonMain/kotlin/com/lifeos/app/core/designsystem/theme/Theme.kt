/**
 * App-wide Material 3 theme. Dark mode is a first-class, always-available
 * theme per docs/06-design-system.md#accessibility, driven by the system
 * setting by default rather than a custom in-app toggle (a manual override
 * can be layered on top of [darkTheme] once Profile/Settings is implemented
 * — profile.png shows a "Karanlık Mod" switch for exactly that).
 *
 * The signature violet gradient (splash, primary buttons, hero cards) is
 * deliberately NOT part of the Material [MaterialTheme.colorScheme] — a
 * `ColorScheme` only holds solid colors. Components that need the gradient
 * reach for [LifeOSGradients] directly.
 */
@Composable
fun LifeOSTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    val colorScheme = if (darkTheme) DarkColors else LightColors

    MaterialTheme(
        colorScheme = colorScheme,
        typography = LifeOSTypography,
        shapes = LifeOSShapes,
        content = content,
    )
}
